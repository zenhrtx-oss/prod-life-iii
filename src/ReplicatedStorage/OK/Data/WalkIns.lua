-- the relationship flags some outcome sets, by visitor (Wave 3, design 4.3: `rel.flag`, for rel.who or else the card's
-- own visitor): { [visitorId] = { [flag] = true } }. Systems/WalkIns keeps only these in prof.walkins.rel (any other flag
-- could never open or close a card)
W.RelFlags = {}
local function indexFlag(item, o)
	local r = type(o) == "table" and o.rel or nil
	if type(r) ~= "table" or type(r.flag) ~= "string" then return end
	local who = r.who or item.visitor
	W.RelFlags[who] = W.RelFlags[who] or {}
	W.RelFlags[who][r.flag] = true
end
for _, list in ipairs({ W.Cards, W.Followups }) do
	for _, item in ipairs(list) do
		if type(item.resolve) == "table" then indexFlag(item, item.resolve.good); indexFlag(item, item.resolve.bad) end
		for _, c in ipairs(item.choices or {}) do indexFlag(item, c.good); indexFlag(item, c.bad); indexFlag(item, c.rare) end
	end
end


local function rosterOf(roster) return roster == "fiction" and "fiction" or "parody" end

-- { [visitorId] = display name } for a roster ("parody" by default). The rep's name still holds {sponsor}.
function W.Names(roster)
	local key, names = rosterOf(roster), {}
	for _, v in ipairs(W.Visitors) do names[v.id] = v.names[key] end
	return names
end

-- a sponsor's display name in a roster; an unknown id comes back as given (nil stays nil)
function W.SponsorName(id, roster)
	local s = id and W.SponsorById[id]
	if not s then return id end
	return s.names[rosterOf(roster)]
end

